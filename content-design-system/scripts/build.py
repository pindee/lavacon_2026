#!/usr/bin/env python3
"""Build everything that is published or consumed by other tools into ./dist.

Outputs:
  dist/rules.json       machine-readable rules (the plugin and the agent read this)
  dist/terms.sch        Schematron rules generated from terms/terms.json
  dist/manifest.json    version plus a hash of every published file (used to detect stale copies)
  dist/standards/       the Markdown standards, for hosting
  dist/index.html       a simple landing page
Standard library only.
"""
import hashlib, html, json, shutil, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIST = ROOT / "dist"

def read_json(rel):
    return json.loads((ROOT / rel).read_text(encoding="utf-8"))

def build_schematron(terms):
    asserts = []
    for t in terms:
        flags = "" if t.get("case_sensitive") else ", 'i'"
        pattern = (r"\b" + t["avoid"] + r"\b").replace("'", "''")
        note = f' {t["notes"]}' if t.get("notes") else ""
        msg = html.escape(f'Use "{t["use"]}" instead of "{t["avoid"]}".{note}', quote=False)
        test = html.escape(f"not(matches(., '{pattern}'{flags}))", quote=True)
        asserts.append(f'      <assert test="{test}">{msg}</assert>')
    body = "\n".join(asserts)
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/build.py from terms/terms.json. Do not edit by hand. -->
<schema xmlns="http://purl.oclc.org/dsdl/schematron" queryBinding="xslt2">
  <title>Terms rules</title>
  <pattern id="terms">
    <!-- Adjust the context to the text-bearing elements of your schema. -->
    <rule context="title | para | p | li | listitem | cmd | shortdesc | entry | stentry">
{body}
    </rule>
  </pattern>
</schema>
'''

def main():
    version = (ROOT / "VERSION").read_text().strip()
    terms = read_json("terms/terms.json")
    checks = read_json("standards/checks.json")

    if DIST.exists():
        shutil.rmtree(DIST)
    DIST.mkdir(parents=True)

    rules = {"version": version, "checks": checks, "terms": terms}
    (DIST / "rules.json").write_text(json.dumps(rules, indent=2) + "\n", encoding="utf-8")
    (DIST / "terms.sch").write_text(build_schematron(terms), encoding="utf-8")
    shutil.copytree(ROOT / "standards", DIST / "standards")

    items = sorted(p.relative_to(DIST).as_posix() for p in DIST.rglob("*") if p.is_file())
    links = "\n".join(f'    <li><a href="{html.escape(i)}">{html.escape(i)}</a></li>' for i in items)
    (DIST / "index.html").write_text(f'''<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>Content Design System</title></head>
<body>
  <h1>Content Design System</h1>
  <p>Version {html.escape(version)}</p>
  <ul>
{links}
  </ul>
</body></html>
''', encoding="utf-8")

    files = sorted(p for p in DIST.rglob("*") if p.is_file())
    manifest = {
        "version": version,
        "files": {p.relative_to(DIST).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest() for p in files},
    }
    (DIST / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Built {len(files)} files into dist/ (version {version}).")

if __name__ == "__main__":
    sys.exit(main())
